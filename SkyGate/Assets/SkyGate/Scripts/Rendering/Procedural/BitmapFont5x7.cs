            "01110,10001,10001,01111,00001,00010,01100", // 9
            "00000,00000,00000,11111,00000,00000,00000", // -
            "00000,00000,00000,00000,00000,01100,01100", // .
            "00000,00000,00000,00000,00000,00000,00000", // space
        };

        static byte[][] _rows;

        static void Init()
        {
            if (_rows != null) return;
            _rows = new byte[Glyphs.Length][];
            for (int g = 0; g < Glyphs.Length; g++)
            {
                var parts = Glyphs[g].Split(',');
                _rows[g] = new byte[7];
                for (int r = 0; r < 7; r++)
                {
                    int v = 0;
                    for (int c = 0; c < 5; c++) v = (v << 1) | (parts[r][c] == '1' ? 1 : 0);
                    _rows[g][r] = (byte)v;
                }
            }
        }

        public static int WidthCells(string text) => Mathf.Max(1, text.Length * 6 - 1);

        /// <summary>Độ phủ tại (u, v) ∈ [0,1]²: u từ trái sang phải, v từ dưới lên trên. Trả 0 hoặc 1.</summary>
        public static float Coverage(string text, float u, float v)
        {
            if (u < 0f || u >= 1f || v < 0f || v >= 1f || string.IsNullOrEmpty(text)) return 0f;
            Init();
            int w = WidthCells(text);
            int cx = Mathf.Min(w - 1, (int)(u * w));
            int cy = Mathf.Min(6, (int)((1f - v) * 7f)); // hàng 0 = trên cùng
            int ch = cx / 6, col = cx % 6;
            if (col >= 5 || ch >= text.Length) return 0f;
            int gi = Chars.IndexOf(char.ToUpperInvariant(text[ch]));
            if (gi < 0) gi = Chars.Length - 1;
            return ((_rows[gi][cy] >> (4 - col)) & 1) == 1 ? 1f : 0f;
        }
    }
